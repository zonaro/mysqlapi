<?php
declare(strict_types=1);

require_once __DIR__ . '/Config.php';

function mysqlapi_install_token_path(): string
{
    return dirname(mysqlapi_env_path()) . '/.mysqlapi-' . substr(hash('sha256', realpath(__DIR__ . '/..') ?: __DIR__), 0, 12) . '-install-token';
}

/** The token is never rendered to an unauthenticated visitor. */
function mysqlapi_bootstrap_token(): string
{
    $configured = getenv('MYSQLAPI_INSTALL_TOKEN');
    if ($configured !== false && strlen($configured) >= 24) {
        return $configured;
    }
    $path = mysqlapi_install_token_path();
    if (is_link($path)) {
        throw new RuntimeException('Invalid installation token file');
    }
    if (!is_file($path)) {
        $previous = umask(0077);
        try {
            $handle = @fopen($path, 'x');
            if ($handle !== false) {
                try {
                    $secret = bin2hex(random_bytes(32));
                    if (fwrite($handle, $secret . "\n") !== strlen($secret) + 1) {
                        throw new RuntimeException('Unable to initialize installation token');
                    }
                } finally {
                    fclose($handle);
                }
                chmod($path, 0600);
            }
        } finally {
            umask($previous);
        }
    }
    $secret = is_file($path) && is_readable($path) ? trim((string) file_get_contents($path)) : '';
    if (strlen($secret) < 24) {
        throw new RuntimeException('Installation token unavailable. Set MYSQLAPI_INSTALL_TOKEN in the PHP environment.');
    }
    return $secret;
}

function mysqlapi_install_configuration(string $providedToken, string $allowedOrigins = ''): string
{
    if (mysqlapi_env_is_public(mysqlapi_env_path())) {
        throw new RuntimeException('Configuration path must be outside the web root');
    }
    if (is_file(mysqlapi_env_path())) {
        throw new RuntimeException('The service is already installed');
    }
    if (!hash_equals(mysqlapi_bootstrap_token(), $providedToken)) {
        throw new InvalidArgumentException('Invalid installation token');
    }
    if (strlen($allowedOrigins) > 2048) {
        throw new InvalidArgumentException('Origin list is too long');
    }
    $origins = array_filter(array_map('trim', explode(',', $allowedOrigins)));
    foreach ($origins as $origin) {
        if (!filter_var($origin, FILTER_VALIDATE_URL) ||
            !preg_match('~^https://[a-z0-9.-]+(?::[0-9]{1,5})?$~iD', $origin)) {
            throw new InvalidArgumentException('CORS origins must be HTTPS origins without paths');
        }
    }
    $envPath = mysqlapi_env_path();
    $keyPath = dirname($envPath) . '/.mysqlapi-' . substr(hash('sha256', realpath(__DIR__ . '/..') ?: __DIR__), 0, 12) . '-private.pem';
    if (file_exists($keyPath) || is_link($keyPath)) {
        throw new RuntimeException('A private key already exists at the installation path; refusing to overwrite it');
    }
    $private = openssl_pkey_new(['private_key_type' => OPENSSL_KEYTYPE_EC, 'curve_name' => 'prime256v1']);
    if ($private === false || !openssl_pkey_export($private, $pem)) {
        throw new RuntimeException('Unable to generate server encryption key');
    }
    $apiKey = bin2hex(random_bytes(32));
    $config = "# Generated by MySqlApi. Keep this file outside the public web root.\n" .
        'MYSQLAPI_PRIVATE_KEY_FILE=' . mysqlapi_env_quote($keyPath) . "\n" .
        'MYSQLAPI_API_KEYS=' . mysqlapi_env_quote($apiKey) . "\n" .
        'MYSQLAPI_ALLOWED_ORIGINS=' . mysqlapi_env_quote(implode(',', $origins)) . "\n";

    $previous = umask(0077);
    $keyHandle = null;
    $envHandle = null;
    $wroteKey = false;
    $wroteEnv = false;
    try {
        $keyHandle = @fopen($keyPath, 'x');
        if (!$keyHandle) {
            throw new RuntimeException('Cannot create the private key outside the web root');
        }
        $wroteKey = true;
        if (fwrite($keyHandle, $pem) !== strlen($pem)) {
            throw new RuntimeException('Unable to write private key');
        }
        fclose($keyHandle);
        $keyHandle = null;
        chmod($keyPath, 0600);

        $envHandle = @fopen($envPath, 'x');
        if (!$envHandle) {
            throw new RuntimeException('Cannot create .env outside the web root');
        }
        $wroteEnv = true;
        if (fwrite($envHandle, $config) !== strlen($config)) {
            throw new RuntimeException('Unable to write .env');
        }
        fclose($envHandle);
        $envHandle = null;
        chmod($envPath, 0600);
    } catch (Throwable $e) {
        if (is_resource($keyHandle)) {
            fclose($keyHandle);
        }
        if (is_resource($envHandle)) {
            fclose($envHandle);
        }
        if ($wroteEnv) {
            @unlink($envPath);
        }
        if ($wroteKey) {
            @unlink($keyPath);
        }
        throw $e;
    } finally {
        umask($previous);
    }
    if (strlen((string) getenv('MYSQLAPI_INSTALL_TOKEN')) < 24) {
        @unlink(mysqlapi_install_token_path());
    }
    return $apiKey;
}

function mysqlapi_install_page(?string $error = null, ?string $newApiKey = null): void
{
    header('Content-Type: text/html; charset=utf-8');
    header("Content-Security-Policy: default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'");
    $escape = static fn (string $value): string => htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    $ready = extension_loaded('openssl') && extension_loaded('mysqli') && PHP_VERSION_ID >= 80100;
    $tokenSource = strlen((string) getenv('MYSQLAPI_INSTALL_TOKEN')) >= 24 ? 'variável MYSQLAPI_INSTALL_TOKEN do servidor' : 'arquivo ' . basename(mysqlapi_install_token_path()) . ' na pasta acima do serviço';
    echo '<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><title>Instalar MySqlApi</title><link rel="stylesheet" href="assets/setup.css"></head><body><main><header><span class="eyebrow">MySqlApi <span class="pill">Instalação</span></span><h1>Vamos preparar<br><span>sua API.</span></h1><p>Configure o serviço uma única vez. A chave privada e o arquivo .env serão criados fora da pasta pública.</p></header><section class="card">';
    if ($newApiKey !== null) {
        echo '<h2>Instalação concluída!</h2><p>Salve agora esta API key: ela é exibida apenas nesta resposta e será necessária para executar consultas.</p><textarea readonly rows="3">' . $escape($newApiKey) . '</textarea><p>Não coloque esta chave em frontend público. Ela está salva no .env privado do servidor.</p><p><a href="./">Abrir o gerador de tokens de banco</a></p>';
    } else {
        echo '<h2>1. Verificação do ambiente</h2><p>PHP 8.1+: ' . (PHP_VERSION_ID >= 80100 ? 'OK' : 'indisponível') . ' · OpenSSL: ' . (extension_loaded('openssl') ? 'OK' : 'indisponível') . ' · MySQLi: ' . (extension_loaded('mysqli') ? 'OK' : 'indisponível') . '</p>';
        echo '<h2>2. Autorize a instalação</h2><p>Para evitar que um visitante configure seu serviço antes de você, leia o segredo no ' . $escape($tokenSource) . '. Ele nunca aparece nesta página. Se não tiver acesso a arquivos, configure a variável de ambiente <code>MYSQLAPI_INSTALL_TOKEN</code> (mínimo 24 caracteres).</p>';
        if ($error !== null) {
            echo '<p class="notice error" role="alert">' . $escape($error) . '</p>';
        }
        echo '<form action="?install" method="post"><div class="fields"><label class="wide">Chave de instalação<input name="install_token" type="password" required autocomplete="off"></label><label class="wide">Origens CORS permitidas (opcional)<input name="allowed_origins" placeholder="https://app.exemplo.com" autocomplete="off"></label></div><button type="submit"' . ($ready ? '' : ' disabled') . '>Instalar serviço →</button></form><p class="hint">O instalador gera automaticamente uma chave privada P-256 e uma API key aleatória. HTTPS e isolamento de rede continuam obrigatórios na implantação pública.</p>';
    }
    echo '</section><footer><a href="https://github.com/zonaro/mysqlapi/blob/main/SECURITY.md">Modelo de segurança</a></footer></main></body></html>';
}
